/**
 * Copies text to the clipboard.
 *
 * The async Clipboard API is only available in secure contexts (`https://`,
 * `http://localhost`, `http://127.0.0.1`, …). On a plain-HTTP origin such as
 * `http://ajapopaja` `navigator.clipboard` is undefined, so fall back to the
 * legacy `document.execCommand('copy')` path in that case (and whenever the
 * async API rejects).
 */
export async function copyToClipboard(text: string): Promise<void> {
  if (navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {
      /* fall through to the legacy path */
    }
  }

  const ta = document.createElement('textarea');
  ta.value = text;
  ta.style.position = 'fixed';
  ta.style.opacity = '0';
  document.body.appendChild(ta);
  ta.focus();
  ta.select();
  try {
    document.execCommand('copy');
  } finally {
    document.body.removeChild(ta);
  }
}
